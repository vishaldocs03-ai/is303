# exponent operator 
calculation = 2 ** 8
print(calculation)

# modulo operator, only returns the remainder of a division
calculation_1 = 5 % 3
print(calculation_1)

# floor division operator, returns the only the quotient of a division, discarding the remainder
calculation_2 = 5 // 3
print(calculation_2)

# rounding
calculation_3 = round(5.6789, 2)
print(calculation_3)

# adding to the value of a variable
account_balance = 1000.00
account_balance = account_balance + 500.00
# this is the same as the line above
account_balance += 500.00
# this divides by 100
account_balance /= 100




